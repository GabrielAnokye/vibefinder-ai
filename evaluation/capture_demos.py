"""
Capture actual CLI output for the demonstration requests into evaluation/results/demo_outputs.md.
Offline and deterministic (template provider); nothing here is a live model response.

    python -m evaluation.capture_demos
"""

import contextlib
import io
from typing import List

from evaluation.common import RESULTS_DIR
from src.main import main

DEMOS: List[List[str]] = [
    ["--ask", "I'm studying for finals. Recommend calm instrumental music with some variety."],
    ["--ask", "I need energetic music for a workout, preferably rock or hip-hop.", "--trace"],
    ["--ask", "Only recommend metal songs."],
    ["--ask", "Recommend acoustic music with very high energy."],
    ["--ask", "Chill lofi music, no repeated artists."],
    ["--ask", "Music for studying."],
    ["--ask", "Music for studying.", "--no-retrieval"],
    ["--ask", "calm music", "--prompt-style", "general"],
]


def run(argv: List[str]) -> str:
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        try:
            main(argv)
        except SystemExit:
            pass
    return buffer.getvalue()


def main_capture() -> None:
    parts = ["# Demonstration outputs (actual, offline)", "",
             "Generated by `python -m evaluation.capture_demos`. Every block is the unedited stdout of the command "
             "shown. Explanations come from the deterministic template provider (not an LLM).", ""]
    for argv in DEMOS:
        shown = " ".join(f'"{a}"' if " " in a else a for a in argv)
        parts += [f"## `python -m src.main {shown}`", "", "```text", run(argv).rstrip(), "```", ""]
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    path = RESULTS_DIR / "demo_outputs.md"
    path.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main_capture()
