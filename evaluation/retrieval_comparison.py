"""
Controlled retrieval experiments (offline, deterministic). Writes evaluation/results/.

1. Retrieval on vs off: identical requests, everything else equal.
2. Single source vs multi-source: an index with only the listening-contexts guide vs the full
   index (both guides + catalog-derived facts).

This measures planning, ranking, citation, and disclosure differences. It is retrieval-driven
planning with template explanations, NOT LLM-based RAG; a changed ranking alone does not show
better recommendations.

    python -m evaluation.retrieval_comparison
"""

from typing import Any, Dict, List

from evaluation.common import cell, snapshot, write_results
from src.assistant import Assistant

ON_OFF_REQUESTS = [
    "Music for studying.",
    "Music for a workout.",
    "Something for a quiet evening.",
    "Recommend acoustic music with very high energy.",
    "Only recommend metal songs.",
    "I'm studying and want energetic music",       # explicit preference must not be overwritten
]
SOURCE_REQUESTS = [
    "Recommend acoustic music with very high energy.",
    "Recommend some metal songs",
    "Only recommend metal songs.",
    "Music for studying.",
    "Something for a quiet evening.",
]
COLUMNS = ["status", "retrieved", "explicit", "inferred", "hints_not_used", "mode", "advanced", "top_ids",
           "distinct_genres", "limitations", "cited_in_limitations", "explanation_citations"]


def compare_on_off(assistant: Assistant) -> List[Dict[str, Any]]:
    return [{"request": text, "on": snapshot(assistant.ask(text)),
             "off": snapshot(assistant.ask(text, retrieval=False))} for text in ON_OFF_REQUESTS]


def compare_sources(full: Assistant, single: Assistant) -> List[Dict[str, Any]]:
    rows = []
    for text in SOURCE_REQUESTS:
        a, b = snapshot(single.ask(text)), snapshot(full.ask(text))
        rows.append({"request": text, "single": a, "multi": b,
                     "evidence_count": {"single": len(a["evidence_sources"]), "multi": len(b["evidence_sources"])},
                     "limitations_with_evidence": {"single": len(a["cited_in_limitations"]),
                                                   "multi": len(b["cited_in_limitations"])}})
    return rows


def _table(rows, left, right, labels) -> List[str]:
    lines = []
    for row in rows:
        lines += [f"### \"{row['request']}\"", "", f"| field | {labels[0]} | {labels[1]} |", "|---|---|---|"]
        lines += [f"| {c} | {cell(row[left][c])} | {cell(row[right][c])} |" for c in COLUMNS]
        lines.append("")
    return lines


def main() -> None:
    full = Assistant()
    single = Assistant(passages=[p for p in full.retriever.passages
                                 if p.source_id.startswith("listening_contexts#")])
    on_off = compare_on_off(full)
    sources = compare_sources(full, single)
    data = {"index_sizes": {"single_source": len(single.retriever.passages), "multi_source": len(full.retriever.passages)},
            "on_off": on_off, "single_vs_multi": sources}

    md = ["# Retrieval comparison (offline, deterministic)", "",
          "Generated by `python -m evaluation.retrieval_comparison`. Explanations come from the deterministic "
          "template provider, so this is retrieval-driven *planning*, not LLM-based RAG. A changed ranking does "
          "not by itself show better recommendations; subjective musical relevance was not measured.", "",
          "## 1. Retrieval on vs off", ""]
    md += _table(on_off, "on", "off", ("retrieval on", "retrieval off"))
    md += ["## 2. Listening-contexts guide only vs all sources", "",
           f"Index sizes: single source {data['index_sizes']['single_source']} passages, "
           f"all sources {data['index_sizes']['multi_source']} passages (the *available* documents; the tables "
           "list the documents actually *retrieved*).", ""]
    md += _table(sources, "single", "multi", ("contexts guide only", "all sources"))
    md += ["| request | evidence passages (single / multi) | limitations backed by a catalog source (single / multi) |",
           "|---|---|---|"]
    md += [f"| {r['request']} | {r['evidence_count']['single']} / {r['evidence_count']['multi']} | "
           f"{r['limitations_with_evidence']['single']} / {r['limitations_with_evidence']['multi']} |" for r in sources]
    md.append("")
    write_results("retrieval_comparison", data, "\n".join(md))


if __name__ == "__main__":
    main()
