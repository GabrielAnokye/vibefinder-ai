"""
Quality-floor and energy-tolerance study (offline, deterministic). Writes evaluation/results/quality_floor.*

The floor drops results scoring below a share of the points available from the ACTIVE
preferences (active_max_score), not the theoretical maximum. The energy tolerance (+/-0.20) only
decides whether a song is reported as meeting a stated energy preference; it never changes scores.
Both are heuristics, not learned or calibrated values.

    python -m evaluation.floor_comparison
"""

from typing import Any, Dict, List

from evaluation.common import write_results
from src.assistant import Assistant
from src.assistant.planner import ENERGY_TOLERANCE, satisfies

FLOORS = [0.0, 0.40, 0.60]
REQUESTS = [
    "Music for studying.",
    "Music for a workout.",
    "Something for a quiet evening.",
    "Chill lofi music",
    "Give me 10 happy songs",
    "sad music with very high energy",
    "Recommend acoustic music with very high energy.",
    "Recommend some metal songs",
]
ENERGY_TARGETS = {"calm / quiet (0.30)": 0.30, "relaxing or studying guide (0.35)": 0.35,
                  "energetic (0.85)": 0.85}
BOUNDARY_BAND = (0.10, 0.30)   # show songs whose |energy - target| falls in this band


def floor_rows() -> List[Dict[str, Any]]:
    rows = []
    for floor in FLOORS:
        assistant = Assistant(quality_floor=floor)
        for text in REQUESTS:
            r = assistant.ask(text)
            shares = [round(x.share_of_active_max, 3) for x in r.recommendations]
            rows.append({
                "floor": floor, "request": text, "status": r.status, "k": r.plan.k if r.plan else None,
                "returned": len(r.recommendations), "shares": shares,
                "weak": sum(1 for x in r.recommendations if x.match_label == "weak"),
                "labels": [x.match_label for x in r.recommendations],
                "short_list_disclosed": any("Returned" in item for item in (r.plan.limitations if r.plan else [])),
            })
    return rows


def boundary_rows(songs: List[Dict]) -> List[Dict[str, Any]]:
    rows = []
    for label, target in ENERGY_TARGETS.items():
        for song in sorted(songs, key=lambda s: abs(s["energy"] - target)):
            gap = abs(song["energy"] - target)
            if BOUNDARY_BAND[0] <= gap <= BOUNDARY_BAND[1]:
                rows.append({"target": label, "song": song["title"], "genre": song["genre"], "mood": song["mood"],
                             "energy": song["energy"], "gap": round(gap, 2),
                             "meets": satisfies(song, "energy", target)})   # the assistant's own rule
    return rows


def main() -> None:
    rows = floor_rows()
    boundary = boundary_rows(Assistant().songs)
    totals = {f: {"returned": sum(r["returned"] for r in rows if r["floor"] == f),
                  "weak": sum(r["weak"] for r in rows if r["floor"] == f),
                  "empty": sum(1 for r in rows if r["floor"] == f and r["returned"] == 0)}
              for f in FLOORS}
    data = {"floors": FLOORS, "energy_tolerance": ENERGY_TOLERANCE, "rows": rows, "totals": totals,
            "energy_boundary": boundary}

    md = ["# Quality floor and energy tolerance (offline)", "",
          "Generated by `python -m evaluation.floor_comparison`. Shares are score / points available from the "
          "active preferences. Labels: strong = share >= 75% and no stated preference missed; partial = share >= 50%; "
          "weak = below 50%. These are heuristics, not learned or calibrated values.", "",
          "## Floors compared", "", "| request | floor | status | returned / k | shares | labels | short list disclosed |",
          "|---|---|---|---|---|---|---|"]
    for text in REQUESTS:
        for r in [r for r in rows if r["request"] == text]:
            md.append(f"| {text} | {r['floor']:.0%} | {r['status']} | {r['returned']} / {r['k']} | "
                      f"{', '.join(f'{s:.0%}' for s in r['shares']) or '-'} | {', '.join(r['labels']) or '-'} | "
                      f"{'yes' if r['short_list_disclosed'] else 'no'} |")
    md += ["", "| floor | total returned | weak matches returned | empty / no-match responses |", "|---|---|---|---|"]
    md += [f"| {f:.0%} | {t['returned']} | {t['weak']} | {t['empty']} |" for f, t in totals.items()]
    md += ["", f"## Energy tolerance (±{ENERGY_TOLERANCE:.2f}) near the boundary", "",
           "Songs whose energy is 0.10–0.30 away from a target the interpreter or a guide produces. "
           "'meets' only affects the 'misses: energy' disclosure, never the score.", "",
           "| target | song | genre / mood | energy | gap | meets |", "|---|---|---|---|---|---|"]
    md += [f"| {b['target']} | {b['song']} | {b['genre']} / {b['mood']} | {b['energy']:.2f} | {b['gap']:.2f} | "
           f"{'yes' if b['meets'] else 'no'} |" for b in boundary]
    md.append("")
    write_results("quality_floor", data, "\n".join(md))


if __name__ == "__main__":
    main()
